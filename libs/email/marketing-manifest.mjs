// Writes emails/marketing/manifest.generated.ts: a static import of every marketing email under
// emails/marketing/ (any depth, .tsx), so the outbox and the studio can render them on Vercel,
// where the folder can't be read at run time. Plain Node (no tsx needed), run before `dev`,
// `build` and `email` (`node libs/email/marketing-manifest.mjs`), and again whenever the studio
// lists emails in development, so a new file shows up without a restart.
// Folders and files starting with "_" are skipped (emails/marketing/_starter).
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "fs"
import { join, relative } from "path"
import { fileURLToPath } from "url"

const ROOT = join(process.cwd(), "emails", "marketing")
const OUT = join(ROOT, "manifest.generated.ts")

/** @param {string} dir @returns {string[]} */
const walk = (dir) =>
  readdirSync(dir)
    .filter((name) => !name.startsWith("_") && !name.startsWith("."))
    .flatMap((name) => {
      const path = join(dir, name)
      if (statSync(path).isDirectory()) return walk(path)
      return name.endsWith(".tsx") ? [path] : []
    })

/** Returns true when the file changed */
export const writeMarketingManifest = () => {
  const files = existsSync(ROOT) ? walk(ROOT).sort() : []
  const keys = files.map((f) => relative(ROOT, f).replace(/\\/g, "/").replace(/\.tsx$/, ""))
  const body = [
    "// Generated by libs/email/marketing-manifest.mjs: don't edit. Every email under emails/marketing/.",
    'import type { MarketingModule } from "../kit/marketing"',
    ...keys.map((k, i) => `import * as m${i} from "./${k}"`),
    "",
    "export const MARKETING_EMAILS: Record<string, MarketingModule> = {",
    ...keys.map((k, i) => `  ${JSON.stringify(k)}: m${i},`),
    "}",
    "",
  ].join("\n")
  if (existsSync(OUT) && readFileSync(OUT, "utf8") === body) return false
  writeFileSync(OUT, body)
  return true
}

// Run directly: `npm run email:marketing-manifest`
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  console.log(writeMarketingManifest() ? "Marketing email manifest updated" : "Marketing email manifest up to date")
}
